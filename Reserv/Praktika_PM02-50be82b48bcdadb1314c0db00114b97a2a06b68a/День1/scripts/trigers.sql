-- Удаляем старые триггеры, если есть
IF EXISTS (SELECT * FROM sys.triggers WHERE name = 'trg_Отклонение_Логирование')
    DROP TRIGGER trg_Отклонение_Логирование;
GO

IF EXISTS (SELECT * FROM sys.triggers WHERE name = 'trg_Проверка_Суммы_Рецептуры')
    DROP TRIGGER trg_Проверка_Суммы_Рецептуры;
GO


-- =====================================================
-- ТРИГГЕР 1: При добавлении отклонения - автоматически логируем в Журнал_событий
-- =====================================================
CREATE TRIGGER trg_Отклонение_Логирование
ON Отклонения
AFTER INSERT
AS
BEGIN
    INSERT INTO Журнал_событий (ид_пользователя, тип_события, сущность, ид_сущности, описание, дата_время)
    SELECT 
        ISNULL(ид_зафиксировал, 1),
        'Отклонение',
        'Отклонения',
        ид_отклонения,
        'Зафиксировано отклонение: ' + ISNULL(тип, 'неизвестный тип') + ' - ' + ISNULL(описание, 'без описания'),
        GETDATE()
    FROM inserted;
END;
GO


-- =====================================================
-- ТРИГГЕР 2: Проверка, что сумма долей в рецептуре не превышает 100%
-- =====================================================
CREATE TRIGGER trg_Проверка_Суммы_Рецептуры
ON Состав_рецептуры
AFTER INSERT, UPDATE
AS
BEGIN
    DECLARE @ид_рецептуры INT;
    DECLARE @сумма DECIMAL(10,2);
    
    SELECT TOP 1 @ид_рецептуры = ид_рецептуры FROM inserted;
    
    IF @ид_рецептуры IS NOT NULL
    BEGIN
        SELECT @сумма = SUM(доля_процент) FROM Состав_рецептуры WHERE ид_рецептуры = @ид_рецептуры;
        
        IF @сумма > 100
        BEGIN
            RAISERROR('Ошибка: сумма долей компонентов не может превышать 100%%', 16, 1);
            ROLLBACK;
        END;
    END;
END;
GO


